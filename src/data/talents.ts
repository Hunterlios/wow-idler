export const talentPoints = (level: number) => Math.max(0, level - 9)
export const spentIn = (cls: ClassId, picks: Record<string, number>, tree: number) =>
  TALENTS[cls].filter((x) => x.tree === tree).reduce((a, x) => a + (picks[x.id] ?? 0), 0)
export const spentTotal = (picks: Record<string, number>) => Object.values(picks).reduce((a, b) => a + b, 0)

export function canLearnTalent(cls: ClassId, picks: Record<string, number>, level: number, id: string): boolean {
  const tl = TALENTS[cls].find((x) => x.id === id)
  if (!tl) return false
  if ((picks[id] ?? 0) >= tl.max) return false
  if (spentTotal(picks) >= talentPoints(level)) return false
  return spentIn(cls, picks, tl.tree) >= tl.tier * 5
}

// Suma efektów talentów
export function talentFx(cls: ClassId, picks: Record<string, number>) {
  const out: Record<string, number> = {}
  for (const tl of TALENTS[cls]) {
    const r = picks[tl.id] ?? 0
    if (!r) continue
    for (const [k, v] of tl.fx) out[k] = (out[k] ?? 0) + v * r
  }
  return out
}
export const talentGrants = (cls: ClassId, picks: Record<string, number>) =>
  new Set(TALENTS[cls].filter((x) => x.grants && (picks[x.id] ?? 0) > 0).map((x) => x.grants!))

export const respecCost = (level: number) => Math.round(level * level * 5)
